import { Tool, ToolMetadata, ToolContext, ToolResult } from '../types.ts';
import { verifyCeovaArtifact } from '../../utils/ceova-watermark.ts';

export class VerifyCeovaProvenanceTool implements Tool {
  metadata: ToolMetadata = {
    id: 'verify_ceova_provenance',
    name: 'Ceova Watermark & Provenance Verifier',
    description: 'Verifies whether an image, file, email, or calendar event was generated or handled by Ceova by checking its hidden cryptographic watermark and provenance signature. Always invoke this when the user asks which image was generated by Ceova, or asks to verify/check a watermark on attached images or files.',
    category: 'Security & Integrity',
    icon: 'shield-check',
    requiresImage: false,
    requiresAuth: false,
    enabled: true,
    parameters: {
      type: 'object',
      properties: {
        artifact_type: {
          type: 'string',
          description: 'Type of artifact to verify: auto, text, email, image, calendar, drive.',
          enum: ['auto', 'text', 'email', 'image', 'calendar', 'drive']
        },
        content: {
          type: 'string',
          description: 'Text snippet, email body, raw email, calendar JSON, or image URL to verify.'
        }
      }
    }
  };

  async execute(context: ToolContext): Promise<ToolResult> {
    const updateStatus = context.onStatusUpdate || (() => {});
    updateStatus('Scanning for Ceova hidden cryptographic watermark…');

    try {
      const args = context.args || {};
      const artifactType = args.artifact_type || 'auto';
      let content = args.content || '';

      // Collect all image attachments
      const imageAttachments = context.attachments?.filter((a: any) => 
        (a.type && a.type.startsWith('image/')) || 
        (a.data && a.data.startsWith('data:image/')) ||
        (a.url && /\.(png|jpe?g|webp|gif)(\?|$)/i.test(a.url))
      ) || [];

      // If user has multiple image attachments, verify each one and provide a comparative analysis
      if (imageAttachments.length > 1) {
        updateStatus(`Inspecting cryptographic watermarks across ${imageAttachments.length} images…`);
        const results = [];

        for (let i = 0; i < imageAttachments.length; i++) {
          const att = imageAttachments[i];
          const imgContent = att.data || att.url || att.content;
          const label = att.name ? `Image ${i + 1} ("${att.name}")` : `Image ${i + 1}`;
          const res = await verifyCeovaArtifact('image', imgContent);
          results.push({ label, res, att, index: i + 1 });
        }

        const ceovaMatches = results.filter(r => r.res.isCeovaVerified);
        let markdownOutput = `### 🛡️ Ceova Provenance & Watermark Verification Report\n\n`;

        if (ceovaMatches.length > 0) {
          markdownOutput += `**Summary**: Found **${ceovaMatches.length}** image(s) verified to be generated by Ceova AI.\n\n`;
          for (const item of results) {
            if (item.res.isCeovaVerified) {
              markdownOutput += `#### ✅ ${item.label} — **AUTHENTIC CEOVA IMAGE**\n` +
                `- **Status**: ✅ **100% Authentic Ceova Artifact**\n` +
                `- **Verification**: Cryptographic HMAC-SHA256 signature is valid and untampered\n` +
                (item.res.timestamp ? `- **Generated At**: ${new Date(item.res.timestamp).toLocaleString()}\n` : '') +
                (item.res.traceId ? `- **Trace ID**: \`${item.res.traceId}\`\n` : '') +
                (item.res.details?.prompt ? `- **Original Prompt**: *"${item.res.details.prompt}"*\n` : '') +
                `\n`;
            } else {
              markdownOutput += `#### ❌ ${item.label} — **NOT GENERATED BY CEOVA**\n` +
                `- **Status**: ❌ No valid Ceova watermark or provenance signature found.\n` +
                `- **Inspection Result**: This image did not originate from Ceova AI, or the hidden watermark was altered/removed.\n\n`;
            }
          }
        } else {
          markdownOutput += `**Summary**: Neither of the inspected images contain a valid Ceova cryptographic watermark.\n\n`;
          for (const item of results) {
            markdownOutput += `- **${item.label}**: ❌ Unverified — ${item.res.message}\n`;
          }
        }

        return {
          success: true,
          data: {
            isCeovaVerified: ceovaMatches.length > 0,
            verifiedCount: ceovaMatches.length,
            results: results.map(r => ({ label: r.label, isVerified: r.res.isCeovaVerified, details: r.res })),
            text: markdownOutput,
            summaryMarkdown: markdownOutput
          }
        };
      }

      // Single attachment or explicit content passed
      const singleImage = imageAttachments[0];
      if (singleImage) {
        content = singleImage.data || singleImage.url || singleImage.content;
      } else if (!content) {
        content = context.message || '';
      }

      if (!content) {
        return {
          success: false,
          error: {
            code: 'MISSING_CONTENT',
            message: 'Please provide text, an email body, a file, or attach an image to verify its Ceova watermark.'
          }
        };
      }

      const result = await verifyCeovaArtifact(artifactType as any, content);

      let markdownOutput = '';
      if (result.isCeovaVerified) {
        markdownOutput = `### 🛡️ Ceova Provenance Verification: **VERIFIED AUTHENTIC**\n\n` +
          `- **Status**: ✅ **100% Authentic Ceova Artifact**\n` +
          `- **Artifact Type**: ${result.typeDetected}\n` +
          `- **Issuer**: ${result.issuer}\n` +
          `- **Generated At**: ${result.timestamp ? new Date(result.timestamp).toLocaleString() : 'Recorded in Signature'}\n` +
          (result.traceId ? `- **Trace ID**: \`${result.traceId}\`\n` : '') +
          (result.details?.prompt ? `- **Original Prompt**: *"${result.details.prompt}"*\n` : '') +
          `- **Tamper Check**: Passed (HMAC-SHA256 signature is valid and untampered)\n\n` +
          `*This item contains a valid invisible cryptographic watermark confirming it was generated by Ceova AI.*`;
      } else {
        markdownOutput = `### ⚠️ Ceova Provenance Verification: **UNVERIFIED / NOT FOUND**\n\n` +
          `- **Status**: ❌ **No Valid Ceova Watermark Found**\n` +
          `- **Reason**: ${result.message}\n` +
          `- **Inspection Result**: The provided ${result.typeDetected} either did not originate from Ceova AI, or the hidden watermark was stripped/altered.`;
      }

      return {
        success: true,
        data: {
          ...result,
          text: markdownOutput,
          summaryMarkdown: markdownOutput
        }
      };

    } catch (err: any) {
      return {
        success: false,
        error: {
          code: 'VERIFICATION_ERROR',
          message: `Failed to verify watermark: ${err.message}`
        }
      };
    }
  }
}
