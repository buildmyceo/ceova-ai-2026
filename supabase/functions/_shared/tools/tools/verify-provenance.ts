import { Tool, ToolMetadata, ToolContext, ToolResult } from '../types.ts';
import { verifyCeovaArtifact } from '../../utils/ceova-watermark.ts';

export class VerifyCeovaProvenanceTool implements Tool {
  metadata: ToolMetadata = {
    id: 'verify_ceova_provenance',
    name: 'Ceova Watermark & Provenance Verifier',
    description: 'Verifies whether an image, email, calendar event, or file was generated or handled by Ceova by checking its hidden, invisible cryptographic watermark.',
    category: 'Security & Integrity',
    icon: 'shield-check',
    requiresImage: false,
    requiresAuth: false,
    enabled: true,
    parameters: {
      type: 'object',
      properties: {
        artifact_type: {
          type: 'string',
          description: 'Type of artifact to verify: auto, text, email, image, calendar, drive.',
          enum: ['auto', 'text', 'email', 'image', 'calendar', 'drive']
        },
        content: {
          type: 'string',
          description: 'Text snippet, email body, raw email, calendar JSON, or image URL to verify.'
        }
      }
    }
  };

  async execute(context: ToolContext): Promise<ToolResult> {
    const updateStatus = context.onStatusUpdate || (() => {});
    updateStatus('Scanning for Ceova hidden cryptographic watermark…');

    try {
      const args = context.args || {};
      const artifactType = args.artifact_type || 'auto';
      let content = args.content || context.message || '';

      // Check if user attached an image
      const imageAttachment = context.attachments?.find((a: any) => a.type?.startsWith('image/'));
      if (imageAttachment) {
        updateStatus('Extracting invisible watermark from image…');
        const imgUrl = imageAttachment.url || imageAttachment.content || imageAttachment.data;
        if (imgUrl) {
          content = imgUrl;
        }
      }

      if (!content) {
        return {
          success: false,
          error: {
            code: 'MISSING_CONTENT',
            message: 'Please provide text, an email body, a file, or attach an image to verify its Ceova watermark.'
          }
        };
      }

      const result = await verifyCeovaArtifact(artifactType as any, content);

      let markdownOutput = '';
      if (result.isCeovaVerified) {
        markdownOutput = `### 🛡️ Ceova Provenance Verification: **VERIFIED AUTHENTIC**\n\n` +
          `- **Status**: ✅ **100% Authentic Ceova Artifact**\n` +
          `- **Artifact Type**: ${result.typeDetected}\n` +
          `- **Issuer**: ${result.issuer}\n` +
          `- **Generated At**: ${result.timestamp ? new Date(result.timestamp).toLocaleString() : 'Recorded in Signature'}\n` +
          (result.traceId ? `- **Trace ID**: \`${result.traceId}\`\n` : '') +
          `- **Tamper Check**: Passed (HMAC-SHA256 signature is valid and untampered)\n\n` +
          `*This item contains a valid invisible cryptographic watermark confirming it was generated by Ceova AI.*`;
      } else {
        markdownOutput = `### ⚠️ Ceova Provenance Verification: **UNVERIFIED / NOT FOUND**\n\n` +
          `- **Status**: ❌ **No Valid Ceova Watermark Found**\n` +
          `- **Reason**: ${result.message}\n` +
          `- **Inspection Result**: The provided ${result.typeDetected} either did not originate from Ceova AI, or the hidden watermark was stripped/altered.`;
      }

      return {
        success: true,
        data: {
          ...result,
          summaryMarkdown: markdownOutput
        }
      };

    } catch (err: any) {
      return {
        success: false,
        error: {
          code: 'VERIFICATION_ERROR',
          message: `Failed to verify watermark: ${err.message}`
        }
      };
    }
  }
}
